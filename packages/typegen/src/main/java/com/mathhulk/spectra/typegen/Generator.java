package com.mathhulk.spectra.typegen;

import java.lang.reflect.Constructor;
import java.lang.reflect.Executable;
import java.lang.reflect.Field;
import java.lang.reflect.GenericArrayType;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.WildcardType;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.stream.Collectors;

/**
 * Generates TypeScript declarations for Java classes as scripts see them through GraalJS: package globals
 * ({@code org.bukkit.Material.STONE}), instance interfaces with every public method and field, and a static side
 * ({@code const Material}) with constructors, static methods, and constants. Nested classes are named
 * {@code Outer$Inner}, matching their binary names.
 *
 * <p>Types outside the generated set become {@code any}; JDK types referenced directly by the target classes are
 * generated too, so common types (List, Map, UUID, CompletableFuture, ...) stay typed.
 */
public final class Generator {
  private static final Set<String> RESERVED = Set.of("break", "case", "catch", "class", "const", "continue",
      "debugger", "default", "delete", "do", "else", "enum", "export", "extends", "false", "finally", "for",
      "function", "if", "import", "in", "instanceof", "new", "null", "return", "super", "switch", "this", "throw",
      "true", "try", "typeof", "var", "void", "while", "with", "yield", "let", "static", "implements", "interface",
      "package", "private", "protected", "public", "await", "arguments", "eval");

  private final Docs docs;
  private final Set<Class<?>> classes = new LinkedHashSet<>();
  private final Set<Class<?>> referenced = new LinkedHashSet<>();
  private boolean collecting;

  public Generator(Docs docs) {
    this.docs = docs;
  }

  /** Whether a class is worth declaring: public, named, not synthetic. */
  public static boolean eligible(Class<?> type) {
    return Modifier.isPublic(type.getModifiers()) && !type.isSynthetic() && !type.isAnonymousClass()
        && !type.isLocalClass() && type.getPackageName().length() > 0;
  }

  /** Generates declarations for {@code targets} plus the JDK classes they reference directly. */
  public String generate(Iterable<Class<?>> targets) {
    for (Class<?> type : targets) {
      if (eligible(type)) {
        classes.add(type);
      }
    }
    // First pass: find referenced JDK types so they can be declared too.
    collecting = true;
    StringBuilder discard = new StringBuilder();
    for (Class<?> type : List.copyOf(classes)) {
      declare(type, discard);
    }
    collecting = false;
    for (Class<?> type : referenced) {
      if (eligible(type)) {
        classes.add(type);
      }
    }

    Map<String, List<Class<?>>> packages = new TreeMap<>();
    for (Class<?> type : classes) {
      packages.computeIfAbsent(type.getPackageName(), p -> new ArrayList<>()).add(type);
    }
    StringBuilder out = new StringBuilder();
    out.append("// Generated by Spectra from the classes available on this server. Do not edit.\n");
    out.append("export {};\n\ndeclare global {\n");
    out.append("  /** A Java class as a script value; its instances are T. Pass it to APIs taking a class. */\n");
    out.append("  interface JavaClass<T> { readonly class: java.lang.Class<T>; readonly __instance?: T }\n\n");
    for (Map.Entry<String, List<Class<?>>> pkg : packages.entrySet()) {
      out.append("  namespace ").append(pkg.getKey()).append(" {\n");
      pkg.getValue().sort(Comparator.comparing(Class::getName));
      for (Class<?> type : pkg.getValue()) {
        declare(type, out);
      }
      out.append("  }\n");
    }
    out.append("}\n");
    return out.toString();
  }

  private static String localName(Class<?> type) {
    return type.getName().substring(type.getPackageName().length() + 1);
  }

  private static String qualified(Class<?> type) {
    return type.getPackageName() + "." + localName(type);
  }

  private static String identifier(String name, int index) {
    String cleaned = name == null || name.isEmpty() ? "arg" + index : name.replaceAll("[^A-Za-z0-9_$]", "_");
    return RESERVED.contains(cleaned) ? cleaned + "_" : cleaned;
  }

  /** {@code name(Simple,Types)}; must match {@link SourceDocs}. */
  static String memberKey(Executable executable) {
    String name = executable instanceof Constructor<?> ? "<init>" : executable.getName();
    return name + "(" + Arrays.stream(executable.getParameterTypes()).map(Generator::simpleName)
        .collect(Collectors.joining(",")) + ")";
  }

  private static String simpleName(Class<?> type) {
    return type.isArray() ? simpleName(type.getComponentType()) + "[]" : type.getSimpleName();
  }

  private void doc(StringBuilder out, String indent, String doc) {
    if (doc == null || doc.isBlank()) {
      return;
    }
    out.append(indent).append("/**\n");
    for (String line : doc.split("\n")) {
      out.append(indent).append(" * ").append(line.strip()).append('\n');
    }
    out.append(indent).append(" */\n");
  }

  private String typeParameters(TypeVariable<?>[] variables, Set<String> scope) {
    if (variables.length == 0) {
      return "";
    }
    List<String> names = new ArrayList<>();
    for (TypeVariable<?> variable : variables) {
      names.add(variable.getName());
      scope.add(variable.getName());
    }
    return "<" + String.join(", ", names) + ">";
  }

  /** Maps a Java type to TypeScript, recording referenced JDK classes during the collecting pass. */
  private String map(Type type, Set<String> scope) {
    if (type instanceof Class<?> c) {
      if (c.isArray()) {
        return map(c.getComponentType(), scope) + "[]";
      }
      if (c == void.class) {
        return "void";
      }
      if (c == boolean.class || c == Boolean.class) {
        return "boolean";
      }
      if (c == char.class || c == Character.class || c == String.class || c == CharSequence.class) {
        return "string";
      }
      if (c.isPrimitive() || Number.class.isAssignableFrom(c) && c.getName().startsWith("java.lang.")) {
        return "number";
      }
      if (c == Object.class) {
        return "any";
      }
      if (!classes.contains(c)) {
        if (collecting && c.getName().startsWith("java.") && eligible(c)) {
          referenced.add(c);
        }
        return "any";
      }
      int parameters = c.getTypeParameters().length;
      return qualified(c) + (parameters == 0 ? "" : "<" + String.join(", ", java.util.Collections.nCopies(parameters,
          "any")) + ">");
    }
    if (type instanceof ParameterizedType parameterized) {
      String raw = map(parameterized.getRawType(), scope);
      if (raw.equals("any") || raw.equals("string") || raw.equals("number") || raw.equals("boolean")) {
        return raw;
      }
      String base = raw.contains("<") ? raw.substring(0, raw.indexOf('<')) : raw;
      return base + "<" + Arrays.stream(parameterized.getActualTypeArguments()).map(arg -> map(arg, scope))
          .collect(Collectors.joining(", ")) + ">";
    }
    if (type instanceof TypeVariable<?> variable) {
      return scope.contains(variable.getName()) ? variable.getName() : "any";
    }
    if (type instanceof WildcardType wildcard) {
      return wildcard.getLowerBounds().length > 0 ? "any" : map(wildcard.getUpperBounds()[0], scope);
    }
    if (type instanceof GenericArrayType array) {
      return map(array.getGenericComponentType(), scope) + "[]";
    }
    return "any";
  }

  private String parameters(Executable executable, Set<String> scope, Docs.Member member) {
    Type[] types = executable.getGenericParameterTypes();
    if (types.length != executable.getParameterCount()) {
      types = executable.getParameterTypes(); // Inner-class constructors include the outer instance.
    }
    List<String> out = new ArrayList<>();
    for (int i = 0; i < types.length; i++) {
      String name = member != null && i < member.parameters().size() ? member.parameters().get(i)
          : executable.getParameters()[i].isNamePresent() ? executable.getParameters()[i].getName() : null;
      boolean varargs = executable.isVarArgs() && i == types.length - 1;
      String mapped = map(types[i], scope);
      out.add((varargs ? "..." : "") + identifier(name, i) + ": " + mapped);
    }
    return String.join(", ", out);
  }

  private static boolean visible(Method method) {
    return Modifier.isPublic(method.getModifiers()) && !method.isSynthetic() && !method.isBridge();
  }

  private void declare(Class<?> type, StringBuilder out) {
    String name = localName(type);
    Set<String> classScope = new HashSet<>();
    String typeParameters = typeParameters(type.getTypeParameters(), classScope);
    String owner = type.getName();

    List<String> supertypes = new ArrayList<>();
    if (type.getGenericSuperclass() != null && type.getSuperclass() != Object.class) {
      String mapped = map(type.getGenericSuperclass(), classScope);
      if (!mapped.equals("any")) {
        supertypes.add(mapped);
      }
    }
    for (Type parent : type.getGenericInterfaces()) {
      String mapped = map(parent, classScope);
      if (!mapped.equals("any") && !mapped.equals("string") && !mapped.equals("number")) {
        supertypes.add(mapped);
      }
    }

    doc(out, "    ", docs.classDoc(owner));
    out.append("    interface ").append(name).append(typeParameters);
    if (!supertypes.isEmpty()) {
      out.append(" extends ").append(String.join(", ", supertypes));
    }
    out.append(" {\n");

    Set<String> methodNames = new HashSet<>();
    List<Method> instanceMethods = new ArrayList<>();
    List<Method> staticMethods = new ArrayList<>();
    Method[] declared;
    try {
      declared = type.getDeclaredMethods();
    } catch (LinkageError e) {
      declared = new Method[0]; // A referenced class is missing at runtime; keep the type, skip its members.
    }
    for (Method method : declared) {
      if (!visible(method)) {
        continue;
      }
      (Modifier.isStatic(method.getModifiers()) ? staticMethods : instanceMethods).add(method);
      if (!Modifier.isStatic(method.getModifiers())) {
        methodNames.add(method.getName());
      }
    }
    instanceMethods.sort(Comparator.comparing(Method::getName).thenComparingInt(Method::getParameterCount));
    for (Method method : instanceMethods) {
      Set<String> scope = new HashSet<>(classScope);
      String methodParameters = typeParameters(method.getTypeParameters(), scope);
      Docs.Member member = docs.member(owner, memberKey(method));
      doc(out, "      ", member == null ? null : member.doc());
      out.append("      ").append(method.getName()).append(methodParameters).append("(")
          .append(parameters(method, scope, member)).append("): ").append(map(method.getGenericReturnType(), scope))
          .append(";\n");
    }
    Field[] fields;
    try {
      fields = type.getDeclaredFields();
    } catch (LinkageError e) {
      fields = new Field[0];
    }
    for (Field field : fields) {
      if (Modifier.isPublic(field.getModifiers()) && !Modifier.isStatic(field.getModifiers())
          && !field.isSynthetic() && !methodNames.contains(field.getName())) {
        out.append("      ").append(Modifier.isFinal(field.getModifiers()) ? "readonly " : "")
            .append(identifier(field.getName(), 0)).append(": ").append(map(field.getGenericType(), classScope))
            .append(";\n");
      }
    }
    out.append("    }\n");

    // Static side: constructors, static methods, constants.
    String instance = name + (type.getTypeParameters().length == 0 ? ""
        : "<" + String.join(", ", java.util.Collections.nCopies(type.getTypeParameters().length, "any")) + ">");
    out.append("    const ").append(name).append(": JavaClass<").append(instance).append("> & {\n");
    if (!type.isInterface() && !Modifier.isAbstract(type.getModifiers())) {
      for (Constructor<?> constructor : type.getConstructors()) {
        Set<String> scope = new HashSet<>(classScope);
        Docs.Member member = docs.member(owner, memberKey(constructor));
        doc(out, "      ", member == null ? null : member.doc());
        out.append("      new").append(typeParameters).append("(").append(parameters(constructor, scope, member))
            .append("): ").append(name).append(typeParameters).append(";\n");
      }
    }
    staticMethods.sort(Comparator.comparing(Method::getName).thenComparingInt(Method::getParameterCount));
    Set<String> staticNames = new HashSet<>();
    for (Method method : staticMethods) {
      Set<String> scope = new HashSet<>();
      String methodParameters = typeParameters(method.getTypeParameters(), scope);
      Docs.Member member = docs.member(owner, memberKey(method));
      doc(out, "      ", member == null ? null : member.doc());
      out.append("      ").append(method.getName()).append(methodParameters).append("(")
          .append(parameters(method, scope, member)).append("): ").append(map(method.getGenericReturnType(), scope))
          .append(";\n");
      staticNames.add(method.getName());
    }
    for (Field field : fields) {
      if (Modifier.isPublic(field.getModifiers()) && Modifier.isStatic(field.getModifiers()) && !field.isSynthetic()
          && !staticNames.contains(field.getName())) {
        Docs.Member member = docs.member(owner, field.getName());
        doc(out, "      ", member == null ? null : member.doc());
        out.append("      ").append(Modifier.isFinal(field.getModifiers()) ? "readonly " : "")
            .append(identifier(field.getName(), 0)).append(": ").append(map(field.getGenericType(), new HashSet<>()))
            .append(";\n");
      }
    }
    out.append("    };\n");
  }
}
